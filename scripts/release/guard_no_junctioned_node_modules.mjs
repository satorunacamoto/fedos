#!/usr/bin/env node
// FedOS Commerce Mainline Integration arc — release/package integrity
// guard.
//
// This repository's own `BUILDING.md`/`CONTRIBUTING.md` document a real,
// established technique for FAST day-to-day worktree setup: junctioning
// `node_modules` from a sibling worktree instead of running a full
// `npm ci`/`npm install`. That is fine for ordinary development and
// typecheck/test iteration.
//
// It is NOT fine for a release/package build. A junctioned `node_modules`
// is a directory some OTHER worktree/branch owns and can mutate at any
// time; its content is whatever that sibling last happened to install,
// not what THIS worktree's own `package.json`/`package-lock.json`
// actually declare. This is not a hypothetical risk — it is exactly the
// mechanism a real investigation traced two silent packaging defects to
// (missing `qrcode`, `@noble/curves`, `dijkstrajs`, `pngjs` from a shipped
// `app.asar`, both caused by the shared/junctioned `node_modules` drifting
// out from under the packaging run — see
// `docs/commerce/evidence/commerce_e2e_packaged_binary/packaged_binary_bootstrap_investigation_2026-08-12_agent_x_p1.md`,
// section "0. Two real, disclosed, PRE-EXISTING environmental defects").
//
// Policy this script mechanically enforces: a release/package validation
// run MUST use a `node_modules` that is a real, standalone directory this
// worktree's own `npm ci` produced — never a Windows junction, never a
// symlink, never missing outright. This is deliberately a cheap presence/
// identity check, not a full integrity-checking system (e.g. it does not
// hash-verify every installed package against the lockfile) — see the
// arc's own mandate for why that tradeoff was chosen.
//
// Usage: node scripts/release/guard_no_junctioned_node_modules.mjs
//   [extra-node_modules-path ...]
//
// With no arguments, checks this repo's two known node_modules locations
// (root, and packages/fedos-desktop-electron-spike). Exit code 0 = every
// checked node_modules is a real, present, non-reparse-point directory.
// Non-zero = at least one is missing or is a junction/symlink (see stdout
// for exactly which, and the remediation instructions).

import { lstatSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = resolve(__dirname, "..", "..");

const DEFAULT_TARGETS = [
  join(REPO_ROOT, "node_modules"),
  join(REPO_ROOT, "packages", "fedos-desktop-electron-spike", "node_modules"),
];

const targets =
  process.argv.length > 2
    ? process.argv.slice(2).map((p) => resolve(p))
    : DEFAULT_TARGETS;

function classify(path) {
  let stat;
  try {
    stat = lstatSync(path);
  } catch {
    return { path, status: "missing" };
  }
  // Node reports both real symlinks AND Windows NTFS junctions (a
  // reparse-point directory alias) as isSymbolicLink() === true via
  // lstat — this is the correct, cheap, cross-platform way to detect
  // either without shelling out to `fsutil reparsepoint query` or
  // parsing `Get-Item`'s LinkType.
  if (stat.isSymbolicLink()) {
    return { path, status: "junction-or-symlink" };
  }
  if (!stat.isDirectory()) {
    return { path, status: "not-a-directory" };
  }
  return { path, status: "ok" };
}

const results = targets.map(classify);
const problems = results.filter((r) => r.status !== "ok");

for (const r of results) {
  const label =
    r.status === "ok"
      ? "OK (real directory)"
      : r.status === "missing"
        ? "MISSING"
        : r.status === "junction-or-symlink"
          ? "JUNCTION/SYMLINK (forbidden for release/package validation)"
          : "NOT A DIRECTORY (unexpected)";
  console.log(`[guard_no_junctioned_node_modules] ${r.path}: ${label}`);
}

if (problems.length > 0) {
  console.error("");
  console.error(
    "[guard_no_junctioned_node_modules] FAILED. Release/package validation" +
      " must run from a worktree whose node_modules directories were" +
      " produced by this worktree's own `npm ci` — never a directory" +
      " junction or symlink shared with another worktree, and never" +
      " missing. Fix:",
  );
  console.error("");
  console.error("    npm ci");
  console.error(
    "    npm ci --prefix packages/fedos-desktop-electron-spike",
  );
  console.error("");
  console.error(
    "If a target above is a JUNCTION/SYMLINK, remove the junction first" +
      " (Windows: `Remove-Item <path>` — this deletes only the junction" +
      " reparse point, not the target directory's real content) before" +
      " running `npm ci`, which refuses to install into an existing" +
      " junction correctly in every observed case.",
  );
  process.exit(1);
}

console.log(
  "[guard_no_junctioned_node_modules] PASS — all checked node_modules are" +
    " real, standalone directories.",
);
