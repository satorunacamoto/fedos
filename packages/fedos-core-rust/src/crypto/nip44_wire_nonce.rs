//! Stage 224 — real NIP-44 v2 wire nonce generation: exactly 32 bytes
//! from the OS CSPRNG (`getrandom::fill`), for the wire format's
//! `nonce` field `docs/nip44_wire_nonce.md` (Stage 215) already reviewed
//! (the HKDF-expand `info` parameter, ALSO carried in the clear as the
//! wire payload's second field — `docs/nip44_wire_payload_layout.md`,
//! Stage 216). Crate-private only — see `src/crypto.rs`'s module-level
//! doc comment for this module's place in the `crypto` tree.
//!
//! [`generate_wire_nonce_internal`] is COMPLETELY INDEPENDENT of this
//! crate's own pre-existing `fedos_aead_nonce_96`/`FedosAeadNonceDecision`/
//! `FedosAeadNonceKind`/`FedosNonceState` (Stage 138) — deliberately NOT
//! shared, NOT generalized into a common "draw N random bytes" helper,
//! and NOT reused by either boundary. `docs/nip44_wire_nonce.md` already
//! named why: 12 bytes vs. 32 bytes, a direct AEAD nonce vs. an
//! HKDF-expand `info` parameter — two separate boundaries that happen to
//! both draw from the OS CSPRNG, exactly as `fedos_random_bytes_32` and
//! `fedos_aead_nonce_96` themselves already stay two separate functions
//! rather than one parameterized by length.
//!
//! **What this module is NOT**: no ChaCha20 stream-cipher call, no
//! HMAC-SHA256 call, no base64, no wire payload construction (see
//! `crypto::nip44_wire_payload`, Stage 225), no public API, no
//! Runtime/Worker/Storage/Relay connection, no new `Cargo.toml`
//! dependency (`getrandom` is already a production dependency since
//! Stage 104).
#![allow(dead_code)]

/// Coarse observable outcome of a [`generate_wire_nonce_internal`] call.
/// No generated byte is exposed through this label itself — only
/// through [`Nip44WireNonceDecision::nonce`] on `Ready`. Crate-private
/// only.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum Nip44WireNonceStatus {
    /// The OS CSPRNG produced the requested 32 nonce bytes.
    Ready,
    /// The OS CSPRNG reported a failure. There is no fallback PRNG and no
    /// degraded output — a SINGLE fixed label, mirroring
    /// `docs/nip44_internal_plan.md` §7's "one label, never distinguishing
    /// why" discipline this crate already applies to decrypt failures.
    InternalFailure,
}

/// The result of a [`generate_wire_nonce_internal`] call. On
/// [`Nip44WireNonceStatus::Ready`], `nonce` holds exactly 32 freshly
/// drawn CSPRNG bytes; on [`Nip44WireNonceStatus::InternalFailure`],
/// `nonce` is `None` — never a zeroed, truncated, counter-derived, or
/// otherwise degraded substitute. `nonce` is a fixed-size `[u8; 32]`,
/// never a `Vec<u8>` — there is no length for a caller to separately
/// validate. Not a secret (it travels in the clear as the wire payload's
/// own second field, per `docs/nip44_wire_payload_layout.md`), so this
/// type is plain returned data, not `SecretHandle`-wrapped, exactly like
/// `FedosAeadNonceDecision` itself.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) struct Nip44WireNonceDecision {
    pub(crate) status: Nip44WireNonceStatus,
    pub(crate) nonce: Option<[u8; 32]>,
}

/// Draw exactly 32 bytes from the OS CSPRNG via `getrandom::fill`, for
/// use as a future NIP-44 v2 wire nonce. Never accepts a caller-supplied
/// length, a seed, a password, or any other parameter, and never derives
/// its output from a counter, a timestamp, or `conversation_key`/
/// `MessageKey` bytes of any kind. Returns
/// [`Nip44WireNonceStatus::Ready`] with the drawn bytes on success; on
/// any CSPRNG failure, returns [`Nip44WireNonceStatus::InternalFailure`]
/// with `nonce: None` — there is no fallback PRNG, no `rand`/`thread_rng`
/// substitute, and no panic (the `Result` `getrandom::fill` returns is
/// matched exhaustively, never `.unwrap()`/`.expect()`-ed). This function
/// is NOT called by, and does NOT call, any encrypt/decrypt/HKDF/HMAC
/// function — it is a standalone nonce-drawing helper only.
pub(crate) fn generate_wire_nonce_internal() -> Nip44WireNonceDecision {
    let mut buf = [0u8; 32];
    match getrandom::fill(&mut buf) {
        Ok(()) => Nip44WireNonceDecision {
            status: Nip44WireNonceStatus::Ready,
            nonce: Some(buf),
        },
        Err(_) => Nip44WireNonceDecision {
            status: Nip44WireNonceStatus::InternalFailure,
            nonce: None,
        },
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn generate_wire_nonce_internal_returns_ready_with_exactly_32_bytes() {
        let decision = generate_wire_nonce_internal();
        assert_eq!(decision.status, Nip44WireNonceStatus::Ready);
        assert!(decision.nonce.is_some());
    }

    #[test]
    fn generate_wire_nonce_internal_two_calls_are_not_obviously_identical() {
        let first = generate_wire_nonce_internal();
        let second = generate_wire_nonce_internal();
        assert_ne!(first.nonce, second.nonce);
    }

    #[test]
    fn generate_wire_nonce_internal_does_not_panic_across_repeated_calls() {
        for _ in 0..64 {
            let decision = generate_wire_nonce_internal();
            assert_eq!(decision.status, Nip44WireNonceStatus::Ready);
        }
    }

    #[test]
    fn nip44_wire_nonce_status_has_no_variant_other_than_the_two_specified() {
        for status in [Nip44WireNonceStatus::Ready, Nip44WireNonceStatus::InternalFailure] {
            match status {
                Nip44WireNonceStatus::Ready => {}
                Nip44WireNonceStatus::InternalFailure => {}
            }
        }
    }
}
